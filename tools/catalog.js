// Run: node tools/catalog.js
// Rebuilds js/catalog.js: the list of tracks with their lesson titles, levels, terms and quizzes, but no demos.
// The site loads only this file up front and fetches a track's full file (tracks/*.js) when a lesson is opened.
// Run it after adding or editing a track; the site warns in the console if a track and the catalog disagree.
// Track order (and so each track's default color) follows the existing catalog; new files are appended by name.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'js', 'catalog.js');

const found = [];
global.document = undefined;
global.Lab = new Proxy({ addTrack: t => found.push(t) }, { get: (o, k) => (k in o ? o[k] : () => {}) });

let order = [];
try {
  order = [...fs.readFileSync(out, 'utf8').matchAll(/"file":\s*"([^"]+)"/g)].map(m => m[1]);
} catch (e) {
  // First run: take the order the tracks used to be listed in index.html.
  order = [...fs.readFileSync(path.join(root, 'index.html'), 'utf8').matchAll(/src="(tracks\/[^"]+\.js)"/g)].map(m => m[1]);
}
const files = fs.readdirSync(path.join(root, 'tracks')).filter(f => f.endsWith('.js')).map(f => 'tracks/' + f);
const ordered = order.filter(f => files.includes(f)).concat(files.filter(f => !order.includes(f)).sort());

const TRACK_KEYS = ['id', 'title', 'description', 'requires', 'hue', 'kind', 'builds', 'stage', 'optional'];
const LESSON_KEYS = ['id', 'title', 'tagline', 'level', 'goals', 'remember', 'terms', 'quiz', 'refs'];
const pick = (o, keys) => Object.fromEntries(keys.filter(k => o[k] !== undefined).map(k => [k, o[k]]));

const list = [];
const failed = [];
const ids = new Set();
for (const file of ordered) {
  found.length = 0;
  delete require.cache[require.resolve(path.join(root, file))];
  try { require(path.join(root, file)); } catch (e) { failed.push(`${file}: ${e.message}`); continue; } // skipped, reported below
  if (found.length !== 1) throw new Error(`${file}: expected one Lab.addTrack call, got ${found.length}`);
  const t = found[0];
  if (ids.has(t.id)) throw new Error(`${file}: duplicate track id "${t.id}"`);
  ids.add(t.id);
  const lessonIds = new Set();
  for (const l of t.lessons) {
    if (lessonIds.has(l.id)) throw new Error(`${file}: duplicate lesson id "${l.id}"`);
    lessonIds.add(l.id);
    if (!Array.isArray(l.quiz) || !l.quiz.length) throw new Error(`${file}: lesson "${l.id}" has no quiz`);
  }
  list.push({ ...pick(t, TRACK_KEYS), file, lessons: t.lessons.map(l => pick(l, LESSON_KEYS)) });
}

const tmp = out + '.' + process.pid + '.tmp';
fs.writeFileSync(tmp, '/* Generated by tools/catalog.js. Do not edit by hand. */\nLab.catalog(' + JSON.stringify(list) + ');\n');
fs.renameSync(tmp, out); // atomic: a page loading mid-run never sees half a file
if (failed.length) { console.error('SKIPPED (fix and rerun):\n  ' + failed.join('\n  ')); process.exitCode = 1; }
console.log(`catalog: ${list.length} tracks, ${list.reduce((a, t) => a + t.lessons.length, 0)} lessons`);
